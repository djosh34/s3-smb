func vectorContext(t *testing.T) PreauthHash {
	t.Helper()
	var context PreauthHash
	copy(context[:], decodeHex(t, preauthVectors[len(preauthVectors)-1].hash))
	return context
}

func TestPreauthVectors(t *testing.T) {
	preauth := NewPreauth()
	if preauth.Sum() != (PreauthHash{}) {
		t.Fatal("initial hash is not zero")
	}
	for i, vector := range preauthVectors {
		preauth.Update(decodeHex(t, vector.message))
		got := preauth.Sum()
		if !bytes.Equal(got[:], decodeHex(t, vector.hash)) {
			t.Fatalf("step %d: hash = %x, want %s", i, got, vector.hash)
		}
	}
	fork := preauth.Fork()
	before := preauth.Sum()
	fork.Update(decodeHex(t, finalSetupVector))
	if fork.Sum() == before || preauth.Sum() != before {
		t.Fatal("fork changed the original transcript or failed to update")
	}
	copyHash := preauth.Sum()
	copyHash[0] ^= 1
	if preauth.Sum() != before {
		t.Fatal("Sum aliases the transcript")
	}
}

func TestKeyDerivationVectors(t *testing.T) {
	key := decodeHex(t, "270E1BA896585EEB7AF3472D3B4C75A7")
	// The 256-bit keys were calculated independently with Python HMAC-SHA256.
	vectors := []struct {
		label string
		key   string
	}{
		{label: "SMBSigningKey", key: "73FE7A9A77BEF0BDE49C650D8CCB5F76"},
		{label: "SMBS2CCipherKey", key: "E2AF0DCEFAC68DA71A0DFBD0D1350D74"},
		{label: "SMBC2SCipherKey", key: "629BCBC54422A0F572B97F45989B6073"},
		{label: "SMBS2CCipherKey", key: "35952fed051bf2471af5f7acc63674b887a54b47af46959f7caff1ce537d7419"},
		{label: "SMBC2SCipherKey", key: "049c27fd8a340262e32c643dea2ba507af7a4c085fd2505aeffcbdeae6d6d8ab"},
	}
	for _, vector := range vectors {
		got, err := deriveKey(key, vector.label, vectorContext(t), len(vector.key)/2)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, decodeHex(t, vector.key)) {
			t.Errorf("%s = %x, want %s", vector.label, got, vector.key)
		}
	}
	if _, err := deriveKey(key, "SMBSigningKey", vectorContext(t), 24); err == nil {
		t.Fatal("accepted an unsupported key length")
	}
}

func TestFinalSetupCMACConcurrent(t *testing.T) {
	protector := newTestProtector(t, smb.SigningCMAC, 0, RoleServer)
	member := decodeHex(t, finalSetupVector)
	expected := bytes.Clone(member[48:64])
	clear(member[48:64])
	var workers sync.WaitGroup
	for range 8 {
		workers.Go(func() {
			for range 10 {
				got, err := protector.Sign(member)
				if err != nil {
					t.Error(err)
					return
				}
				if !bytes.Equal(got[:], expected) {
					t.Errorf("CMAC = %s, want %x", hex.EncodeToString(got[:]), expected)
					return
				}
				signed := bytes.Clone(member)
				copy(signed[48:64], got[:])
				if err := protector.Verify(signed); err != nil {
					t.Error(err)
				}
			}
		})
	}
	workers.Wait()
}
